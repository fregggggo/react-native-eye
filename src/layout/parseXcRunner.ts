const APPLICATION = 2;
const WINDOW = 4;
const STATUS_BAR = 25;
const SCROLL_BAR = 47;

export function xcTypeName(t: number | undefined): string | undefined {
  if (typeof t !== "number") return undefined;
  return XC_TYPE_NAMES[t] ?? `ElementType${t}`;
}

const num = (v: unknown): number | undefined => (typeof v === "number" && Number.isFinite(v) ? v : undefined);

function rect(frame: XcNode["frame"]): Viewport | undefined {
  if (!frame || typeof frame !== "object") return undefined;
  const x = num(frame.X);
  const y = num(frame.Y);
  const w = num(frame.Width);
  const h = num(frame.Height);
  if (x === undefined || y === undefined || w === undefined || h === undefined) return undefined;
  return { x, y, w, h };
}

/** A usable string: non-empty after trimming. Numbers (a Switch's "1") read as text. */
function str(v: unknown): string | undefined {
  if (typeof v === "number" && Number.isFinite(v)) return String(v);
  return typeof v === "string" && v.trim() !== "" ? v : undefined;
}

/** Drops identifiers that are absolute file paths. */
function fileId(id: string | undefined): string | undefined {
  return id !== undefined && /^\/.*\.[a-z0-9]{2,5}$/i.test(id) ? undefined : id;
}

function rootOf(json: unknown): XcNode | undefined {
  if (!json || typeof json !== "object") return undefined;
  const root = "axElement" in (json as object) ? (json as { axElement: unknown }).axElement : json;
  return root && typeof root === "object" ? (root as XcNode) : undefined;
}

function childrenOf(n: XcNode): XcNode[] {
  return Array.isArray(n.children) ? n.children.filter((c): c is XcNode => !!c && typeof c === "object") : [];
}

/**
 * The screen the elements are clipped to: the first Application frame in tree
 * order; in the runner's recovery shape (no Application) the largest Window.
 */
export function xcRunnerViewport(json: unknown): Viewport | undefined {
  const root = rootOf(json);
  if (!root) return undefined;
  let app: Viewport | undefined;
  let win: Viewport | undefined;
  const visit = (n: XcNode): void => {
    if (app) return;
    const r = rect(n.frame);
    if (r && r.w > 0 && r.h > 0) {
      if (n.elementType === APPLICATION) {
        app = r;
        return;
      }
      if (n.elementType === WINDOW && (!win || r.w * r.h > win.w * win.h)) win = r;
    }
    for (const c of childrenOf(n)) visit(c);
  };
  visit(root);
  return app ?? win;
}

/**
 * The runner's hierarchy as the same flat element list parseAxe produces, so
 * search, selectors and tap targeting behave identically on both paths.
 */
export function parseXcRunner(json: unknown, fallbackViewport?: { w: number; h: number }): RawElement[] {
  const root = rootOf(json);
  if (!root) return [];
  const viewport =
    xcRunnerViewport(json) ?? (fallbackViewport ? { x: 0, y: 0, w: fallbackViewport.w, h: fallbackViewport.h } : undefined);

  const out: RawElement[] = [];
  const seen = new Set<string>();
  const visit = (n: XcNode): void => {
    const t = n.elementType;
    // The status bar (clock, signal, battery) is SpringBoard chrome, and a
    // scroll bar's thumb is not a control: neither subtree has anything to tap.
    if (t === STATUS_BAR || t === SCROLL_BAR) return;
    const text = str(n.label) ?? str(n.value) ?? str(n.placeholderValue);
    // UIKit uses an image's file path as its identifier (the ATT alert's icon
    // is a file under the simulator's data dir); that is no test ID.
    const testID = fileId(str(n.identifier));
    const r = rect(n.frame);
    if (r && (text || testID) && t !== APPLICATION && t !== WINDOW && r.w > 0 && r.h > 0 && !SYSTEM_LABEL_RE.test(text ?? "")) {
      const el: RawElement = { x: r.x, y: r.y, w: r.w, h: r.h };
      if (text !== undefined) el.text = text;
      if (testID !== undefined) el.testID = testID;
      const type = xcTypeName(t);
      if (type !== undefined) el.type = type;
      const dedupe = `${el.text ?? ""}|${el.testID ?? ""}|${el.x},${el.y},${el.w},${el.h}`;
      if (!seen.has(dedupe)) {
        seen.add(dedupe);
        const vis = clipToViewport(el, viewport);
        if (!vis) el.offscreen = true;
        else if (vis.x !== el.x || vis.y !== el.y || vis.w !== el.w || vis.h !== el.h) el.visible = vis;
        out.push(el);
      }
    }
    for (const c of childrenOf(n)) visit(c);
  };
  visit(root);
  return out;
}
