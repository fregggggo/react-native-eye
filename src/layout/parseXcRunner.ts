/**
 * One node of the runner's `/viewHierarchy` answer (`{axElement, depth}`): an
 * XCUIElement snapshot. Frames are points, capitalised, and already shifted into
 * screen coordinates by the runner — this parser adds no offsets.
 */
export type XcNode = {
  elementType?: number;
  label?: string | null;
  identifier?: string | null;
  value?: unknown;
  placeholderValue?: string | null;
  frame?: { X?: unknown; Y?: unknown; Width?: unknown; Height?: unknown } | null;
  children?: XcNode[] | null;
};

